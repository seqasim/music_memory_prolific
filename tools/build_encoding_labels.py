#!/usr/bin/env python3
"""Build person-count labels for encoding videos from Memento10k captions.

Writes stimuli/encoding_video_labels.auto.json. After review, copy to
stimuli/encoding_video_labels.json (or pass --confirm to overwrite confirmed).

Labels: one_or_fewer | multiple | ambiguous

Usage:
  python3 tools/build_encoding_labels.py
  python3 tools/build_encoding_labels.py --confirm
"""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DB = Path("/Users/salmanqasim/Documents/Projects/MusicMemory/video_database_full")
AUTO_PATH = ROOT / "stimuli" / "encoding_video_labels.auto.json"
CONFIRMED_PATH = ROOT / "stimuli" / "encoding_video_labels.json"

MULTI_RE = re.compile(
    r"\b("
    r"people|persons|men|women|children|kids|crowd|group|couple|friends|family|team|"
    r"players|spectators|audience|"
    r"two (men|women|people|boys|girls|children|kids|persons)|"
    r"three |several |many |a group"
    r")\b",
    re.I,
)
ONE_RE = re.compile(
    r"\b("
    r"a (man|woman|boy|girl|person|child|baby|toddler|guy|lady)|"
    r"an (adult|elderly)|"
    r"someone|"
    r"the (man|woman|boy|girl|person|child|baby|toddler)"
    r")\b",
    re.I,
)
PERSON_RE = re.compile(
    r"\b(person|people|man|woman|men|women|boy|girl|child|children|baby|toddler|"
    r"someone|human|crowd|spectators|audience)\b",
    re.I,
)
ANIMAL_RE = re.compile(
    r"\b(dog|cat|bird|horse|fish|puppy|kitten|animal|goat|hamster|turtle)\b",
    re.I,
)


def load_memento_records(db: Path) -> dict[str, dict]:
    records: dict[str, dict] = {}
    for name in (
        "memento_train_data.json",
        "memento_val_data.json",
        "memento_test_data.json",
    ):
        for rec in json.loads((db / name).read_text(encoding="utf-8")):
            records[rec["filename"]] = rec
    return records


def classify(rec: dict) -> tuple[str, str, dict]:
    """Return (label, strength, vote_counts)."""
    texts = list(rec.get("captions") or []) + [rec.get("audio_description") or ""]
    multi_votes = sum(1 for t in texts if MULTI_RE.search(t))
    one_votes = sum(1 for t in texts if ONE_RE.search(t) and not MULTI_RE.search(t))
    animal_only = sum(
        1 for t in texts if ANIMAL_RE.search(t) and not PERSON_RE.search(t)
    )
    votes = {
        "multi_votes": multi_votes,
        "one_votes": one_votes,
        "animal_only": animal_only,
    }

    # No people (animals / empty scenes) → one_or_fewer
    if animal_only >= 3 and multi_votes == 0:
        return "one_or_fewer", "strong", votes

    if multi_votes >= 2 and multi_votes > one_votes:
        return "multiple", "strong", votes
    if one_votes >= 2 and one_votes > multi_votes:
        return "one_or_fewer", "strong", votes

    if multi_votes > one_votes:
        return "multiple", "weak", votes
    if one_votes > multi_votes:
        return "one_or_fewer", "weak", votes
    if animal_only > 0 and multi_votes == 0:
        return "one_or_fewer", "weak", votes

    return "ambiguous", "ambiguous", votes


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    parser.add_argument(
        "--confirm",
        action="store_true",
        help="Also write stimuli/encoding_video_labels.json from auto labels",
    )
    args = parser.parse_args()

    records = load_memento_records(args.db)
    encoding_dir = ROOT / "stimuli" / "encoding_videos"
    files = sorted(p.name for p in encoding_dir.glob("*.mp4"))
    missing = [f for f in files if f not in records]
    if missing:
        raise SystemExit(f"Missing Memento records for {missing[:5]} (+{max(0,len(missing)-5)})")

    labels: dict[str, str] = {}
    needs_review: list[dict] = []
    counts: Counter[str] = Counter()
    strength_counts: Counter[str] = Counter()

    for base in files:
        label, strength, votes = classify(records[base])
        labels[base] = label
        counts[label] += 1
        strength_counts[strength] += 1
        if strength != "strong":
            needs_review.append(
                {
                    "filename": base,
                    "label": label,
                    "strength": strength,
                    "votes": votes,
                    "caption0": (records[base].get("captions") or [""])[0],
                    "audio_description": (records[base].get("audio_description") or "")[:160],
                }
            )

    out: dict = {
        "_meta": {
            "description": "Person-count labels for encoding orienting (Memento10k captions).",
            "source": "Memento10k; auto-generated by tools/build_encoding_labels.py",
            "values": ["one_or_fewer", "multiple", "ambiguous"],
            "scoring_note": "Ambiguous clips leave encoding orienting correct blank.",
            "n_videos": len(files),
            "n_one_or_fewer": counts["one_or_fewer"],
            "n_multiple": counts["multiple"],
            "n_ambiguous": counts["ambiguous"],
            "n_strong": strength_counts["strong"],
            "n_weak": strength_counts["weak"],
            "needs_review": needs_review,
        }
    }
    for base, label in labels.items():
        out[base] = label
        out[f"stimuli/encoding_videos/{base}"] = label

    AUTO_PATH.write_text(json.dumps(out, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"Wrote {AUTO_PATH}")
    print(
        f"  one_or_fewer={counts['one_or_fewer']} multiple={counts['multiple']} "
        f"ambiguous={counts['ambiguous']} needs_review={len(needs_review)}"
    )

    if args.confirm:
        # Confirmed file omits the bulky needs_review list (keep counts).
        confirmed = json.loads(json.dumps(out))
        confirmed["_meta"].pop("needs_review", None)
        confirmed["_meta"]["confirmed"] = True
        confirmed["_meta"][
            "description"
        ] = "Person-count labels for encoding orienting. Confirm before production."
        CONFIRMED_PATH.write_text(
            json.dumps(confirmed, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        print(f"Wrote {CONFIRMED_PATH} (--confirm)")


if __name__ == "__main__":
    main()
